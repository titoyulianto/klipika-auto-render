const { google } = require('googleapis');
const fs = require('fs');
const { pipeline } = require('stream');
const { promisify } = require('util');
const streamPipeline = promisify(pipeline);

const CLIENT_ID = process.env.YOUTUBE_CLIENT_ID;
const CLIENT_SECRET = process.env.YOUTUBE_CLIENT_SECRET;
const REFRESH_TOKEN = process.env.YOUTUBE_REFRESH_TOKEN;

const VIDEO_URL = process.env.VIDEO_URL;
const VIDEO_TITLE = process.env.VIDEO_TITLE || "Berita Terkini #shorts";
const VIDEO_DESC = process.env.VIDEO_DESC || "Generated by Klipika Studio";

if (!VIDEO_URL) {
    console.error("❌ ERROR: URL Video dari Cloud tidak ditemukan!");
    process.exit(1);
}

const oauth2Client = new google.auth.OAuth2(CLIENT_ID, CLIENT_SECRET);
oauth2Client.setCredentials({ refresh_token: REFRESH_TOKEN });

const youtube = google.youtube({
    version: 'v3',
    auth: oauth2Client
});

async function downloadAndUpload() {
    try {
        console.log(`📥 [1/2] Mendownload video utuh dari cloud: ${VIDEO_URL}`);
        
        const res = await fetch(VIDEO_URL);
        if (!res.ok) throw new Error(`Gagal mendownload video dari URL: ${res.statusText}`);
        
        const videoPath = './temp_video.webm';
        const fileStream = fs.createWriteStream(videoPath);
        
        // Menggunakan stream pipeline agar file video .webm tidak corrupt/rusak
        await streamPipeline(res.body, fileStream);
        
        console.log("✅ Video berhasil diunduh ke server lokal GitHub dengan sempurna.");

        console.log("🚀 [2/2] Mengunggah video ke YouTube Shorts...");
        const response = await youtube.videos.insert({
            part: 'snippet,status',
            requestBody: {
                snippet: {
                    title: VIDEO_TITLE,
                    description: VIDEO_DESC,
                    tags: ["beritaterkini", "shorts", "viral"],
                    categoryId: '25' // News & Politics
                },
                status: {
                    privacyStatus: 'public',
                    selfDeclaredMadeForKids: false
                }
            },
            media: {
                body: fs.createReadStream(videoPath)
            }
        });

        console.log(`🎉 BINGO! Video berhasil di-upload ke YouTube!`);
        console.log(`🔗 Link Video: https://youtu.be/${response.data.id}`);

        // Bersihkan file temp lokal
        fs.unlinkSync(videoPath);
    } catch (error) {
        console.error("❌ Gagal saat proses upload ke YouTube:", error.message);
        process.exit(1);
    }
}

downloadAndUpload();
